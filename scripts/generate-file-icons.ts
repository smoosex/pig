/* Copy only referenced SVGs into the renderer's static assets. */
import { cp, mkdir, rm, writeFile } from 'node:fs/promises'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { generateManifest } from 'material-icon-theme'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const packageRoot = join(root, 'node_modules/material-icon-theme')
const source = join(packageRoot, 'icons')
const publicDir = join(root, 'src/renderer/public')
const iconsDir = join(publicDir, 'file-icons')
const output = join(root, 'src/renderer/src/lib/file-icons.generated.ts')
const manifest = generateManifest({ activeIconPack: '' })
const fileNames = manifest.fileNames ?? {}
const extensions = manifest.fileExtensions ?? {}
const ids = new Set([...Object.values(fileNames), ...Object.values(extensions)])

await rm(iconsDir, { recursive: true, force: true })
await rm(join(publicDir, 'file-icons-LICENSE.txt'), { force: true })
await mkdir(iconsDir, { recursive: true })
for (const id of [...ids].sort()) {
  const iconPath = manifest.iconDefinitions?.[id]?.iconPath
  if (!iconPath) throw new Error(`Missing icon definition: ${id}`)
  await cp(join(source, basename(iconPath)), join(iconsDir, `${id}.svg`))
}
await cp(join(packageRoot, 'LICENSE'), join(iconsDir, 'LICENSE'))

await writeFile(output, [
  '/* Generated by scripts/generate-file-icons.ts; do not edit. */',
  `export const fileNames: Record<string, string> = ${JSON.stringify(fileNames)}`,
  `export const extensions: Record<string, string> = ${JSON.stringify(extensions)}`,
  ''
].join('\n'))

console.log(`Generated ${ids.size} file icons`)
