import { test } from 'bun:test'
import assert from 'node:assert/strict'
import { mkdtempSync, realpathSync, readFileSync, existsSync, mkdirSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { DreamStage } from '../src/main/features/memory/dream/staging'
import { MemoryFiles } from '../src/main/features/memory/long-term/files'

test('Dream initializes empty stores, publishes with backups, enforces scopes and detects concurrent writes', () => {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'pig-dream-stage-')))
  const live = new MemoryFiles(join(root, 'live'))
  try {
    const first = new DreamStage(join(root, 'first'), live)
    first.store.save('global/MEMORY.md', '[Testing](testing.md)', null)
    first.store.save('global/testing.md', 'A useful testing rule', null)
    assert.deepEqual(live.list(), [], 'staged memories remain invisible')
    assert.equal(first.publish(new Set(['global']), () => {}).length, 2)
    const second = new DreamStage(join(root, 'second'), live)
    const file = second.store.read('global/testing.md')
    second.store.save(file.path, 'A corrected testing rule', file.revision)
    second.publish(new Set(['global']), () => {})
    assert.equal(readFileSync(join(root, 'second', 'before', file.path), 'utf8'), file.content)
    const third = new DreamStage(join(root, 'third'), live)
    third.store.save('global/new.md', 'Pending', null)
    live.save('global/concurrent.md', 'Keep it', null)
    assert.throws(() => third.publish(new Set(['global']), () => {}), /DREAM_CONFLICT/)
    assert.equal(live.optional('global/new.md'), undefined)
    assert.equal(live.read('global/concurrent.md').content, 'Keep it')
    const fourth = new DreamStage(join(root, 'fourth'), live)
    fourth.store.save('global/escape.md', 'Wrong scope', null)
    assert.throws(() => fourth.publish(new Set(['projects/example']), () => {}), /DREAM_SCOPE/)
    const fifth = new DreamStage(join(root, 'fifth'), live)
    const removed = fifth.store.read('global/testing.md')
    fifth.store.delete(removed.path, removed.revision)
    assert.throws(() => fifth.publish(new Set(['global']), () => {}), /DREAM_LINK/)
    const index = fifth.store.read('global/MEMORY.md')
    fifth.store.save(index.path, 'No longer needed', index.revision)
    fifth.publish(new Set(['global']), () => {})
    assert.equal(live.optional(removed.path), undefined)
    live.save('global/legacy.md', '[Old source](../../source.md)', null)
    const unrelated = new DreamStage(join(root, 'unrelated'), live)
    unrelated.store.save('global/unrelated.md', 'A new unrelated clue', null)
    unrelated.publish(new Set(['global']), () => {})
    assert.equal(live.read('global/legacy.md').content, '[Old source](../../source.md)')
    assert.equal(live.read('global/unrelated.md').content, 'A new unrelated clue')
    const unrelatedDeletion = new DreamStage(join(root, 'unrelated-deletion'), live)
    const unrelatedFile = unrelatedDeletion.store.read('global/unrelated.md')
    unrelatedDeletion.store.delete(unrelatedFile.path, unrelatedFile.revision)
    unrelatedDeletion.publish(new Set(['global']), () => {})
    assert.equal(live.optional(unrelatedFile.path), undefined, 'unrelated legacy links do not block deletions either')
    const changedLegacy = new DreamStage(join(root, 'changed-legacy'), live)
    const legacy = changedLegacy.store.read('global/legacy.md')
    changedLegacy.store.save(legacy.path, legacy.content + '\nChanged', legacy.revision)
    assert.throws(() => changedLegacy.publish(new Set(['global']), () => {}), error => (error as { code?: string }).code === 'MEMORY_LINK_OUTSIDE_SCOPE')
    const cancelled = new DreamStage(join(root, 'cancelled'), live)
    cancelled.store.save('global/cancelled.md', 'Do not publish', null)
    assert.throws(() => cancelled.publish(new Set(['global']), () => { throw new Error('cancelled') }), /cancelled/)
    assert.equal(existsSync(join(root, 'live', 'global', 'cancelled.md')), false)
  } finally { rmSync(root, { recursive: true, force: true }) }
})

test('Dream checks the live entry budget, including empty directories, before any publication', () => {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'pig-dream-capacity-')))
  const live = new MemoryFiles(join(root, 'live'))
  try {
    live.save('global/MEMORY.md', 'Existing clue', null)
    for (let index = 0; index < 1996; index++) mkdirSync(join(live.root, `empty-${index}`))
    const stage = new DreamStage(join(root, 'over-limit'), live)
    for (const name of ['a', 'b', 'c']) stage.store.save(`global/${name}.md`, 'New clue', null)
    assert.throws(() => stage.publish(new Set(['global']), () => {}), error => (error as { code?: string }).code === 'MEMORY_SCAN_LIMIT')
    assert.deepEqual(live.list().map(file => file.path), ['global/MEMORY.md'])
    assert.equal(existsSync(join(stage.directory, 'changes.json')), false)
    const nested = new DreamStage(join(root, 'nested-over-limit'), live)
    for (const name of ['a', 'b']) nested.store.save(`global/new/${name}.md`, 'New clue', null)
    assert.throws(() => nested.publish(new Set(['global']), () => {}), error => (error as { code?: string }).code === 'MEMORY_SCAN_LIMIT')
    assert.equal(existsSync(join(live.root, 'global', 'new')), false, 'missing parent directories count before creating them')
    assert.deepEqual(live.list().map(file => file.path), ['global/MEMORY.md'])
    const excess = stage.store.read('global/c.md')
    stage.store.delete(excess.path, excess.revision)
    stage.publish(new Set(['global']), () => {})
    assert.equal(live.list().length, 3, 'a batch exactly at the live limit remains readable')
    const replacement = new DreamStage(join(root, 'replacement'), live)
    const removed = replacement.store.read('global/a.md')
    replacement.store.delete(removed.path, removed.revision)
    replacement.store.save('global/d.md', 'Replacement clue', null)
    replacement.publish(new Set(['global']), () => {})
    assert.equal(live.list().length, 3, 'planned file deletions free capacity for additions')
    assert.equal(live.optional(removed.path), undefined)
    assert.equal(live.read('global/d.md').content, 'Replacement clue')
  } finally { rmSync(root, { recursive: true, force: true }) }
})
